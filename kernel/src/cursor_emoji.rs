static SPRITES: [&[u8; 256]; SPRITE_STYLES] = [&S0, &S1, &S2, &S3, &S4, &S5, &S6, &S7];

pub fn label(preset: u8) -> &'static [u8] {
    let i = (preset as usize) % SPRITE_STYLES;
    match i {
        0 => b"POINTER",
        1 => b"SMILE",
        2 => b"HEART",
        3 => b"STAR",
        4 => b"ROCKET",
        5 => b"CAT",
        6 => b"THUMBS",
        _ => b"RAINBOW",
    }
}

fn put_pixel(buf: &mut [u8], info: &FrameBufferInfo, x: usize, y: usize, r: u8, g: u8, b: u8) {
    if x >= info.width || y >= info.height {
        return;
    }
    let bpp = info.bytes_per_pixel;
    let stride = info.stride;
    let i = y * stride * bpp + x * bpp;
    if i + bpp > buf.len() {
        return;
    }
    match info.pixel_format {
        PixelFormat::Rgb => {
            buf[i] = r;
            buf[i + 1] = g;
            buf[i + 2] = b;
        }
        PixelFormat::Bgr => {
            buf[i] = b;
            buf[i + 1] = g;
            buf[i + 2] = r;
        }
        PixelFormat::U8 => {
            let v = ((r as u16 + g as u16 + b as u16) / 3) as u8;
            buf[i] = v;
        }
        _ => {}
    }
}

/// Draw preset sprite centered on `(cx, cy)`. `pointer_idx` shifts which of the eight themes is used.
pub fn draw_sprite(
    buf: &mut [u8],
    info: &FrameBufferInfo,
    cx: i32,
    cy: i32,
    preset: u8,
    pointer_idx: usize,
) {
    let w = info.width as i32;
    let h = info.height as i32;
    if cx < 0 || cy < 0 || cx >= w || cy >= h {
        return;
    }
    let style = (preset as usize + pointer_idx) % SPRITE_STYLES;
    let data = SPRITES[style];
    let ox = cx - SPRITE / 2;
    let oy = cy - SPRITE / 2;
    for py in 0..SPRITE {
        for px in 0..SPRITE {
            let idx = (py * SPRITE + px) as usize;
            let p = data[idx] as usize;
            if p == 0 {
                continue;
            }
            if p >= PALETTE.len() {
                continue;
            }
            let (r, g, b) = PALETTE[p];
            let sx = ox + px;
            let sy = oy + py;
            if sx >= 0 && sy >= 0 && sx < w && sy < h {
                put_pixel(buf, info, sx as usize, sy as usize, r, g, b);
            }
        }
    }
}
